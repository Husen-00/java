import java.util.*;
import java.lang.*;
import java.io.*;
class Codechef
{
	public static void main (String[] args) throws java.lang.Exception
	{
	    Scanner input = new Scanner (System.in);
	    int a = input.nextInt();
	    int b = input.nextInt();
	    if (a>b) {
	        System.out.println(a);
	    }
	    else {
	        System.out.println(b);
	    }
	}
}
